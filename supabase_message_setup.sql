-- Supabase table & RLS policies for public.message
create table if not exists public.message (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  sender text,
  receiver text,
  content text
);

alter table public.message enable row level security;

-- Allow read access for all users (SELECT)
create policy "Enable read access for all users"
on "public"."message"
as PERMISSIVE
for SELECT
to public
using (
  true
);

-- Allow insert for authenticated users only (INSERT)
create policy "Enable insert for authenticated users only"
on "public"."message"
as PERMISSIVE
for INSERT
to authenticated
with check (
  true
);
